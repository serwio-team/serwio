const { chromium } = await import(process.env.PLAYWRIGHT_MODULE_URL ?? 'playwright-core');
import assert from 'node:assert/strict';
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH ?? 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const baseURL = process.env.SERWIO_TEST_URL ?? 'http://127.0.0.1:5173';
assert.ok(process.env.SEED_PASSWORD, 'Set SEED_PASSWORD for the isolated temporary test backend.');
const context = await browser.newContext({ baseURL, timezoneId: 'America/Los_Angeles' });
const page = await context.newPage();
const runtimeErrors = [];
page.on('pageerror', e => runtimeErrors.push(e.message));
const ok = name => console.log('PASS ' + name);
const visible = locator => locator.waitFor({ state: 'visible', timeout: 15000 });
async function login(target, email) {
  await target.goto('/sign-in');
  await target.locator('[name=username]').fill(email);
  await target.locator('[name=password]').fill(process.env.SEED_PASSWORD);
  await target.getByRole('button', { name: 'Zaloguj się', exact: true }).click();
}
try {
  await login(page, 'owner@example.com');
  const open = page.getByRole('button', { name: 'Dostępność: Lokalizacja testowa', exact: true });
  await visible(open);
  await open.click();
  const dialog = page.getByRole('dialog');
  await visible(dialog.getByText('Brak dostępności w całym tygodniu.'));
  assert.ok((await dialog.innerText()).includes('Europe/Warsaw'));
  assert.ok(!(await dialog.innerText()).includes('America/Los_Angeles'));
  ok('real GET, owner action, empty week, API timezone independent of browser');
  const add = day => dialog.getByRole('button', { name: `Dodaj przedział: ${day}`, exact: true }).click();
  const input = (day, index, endpoint) => dialog.getByRole('textbox', { name: `${day}, przedział ${index}, ${endpoint}`, exact: true });
  const save = dialog.getByRole('button', { name: 'Zapisz dostępność', exact: true });
  await add('Niedziela');
  await input('Niedziela', 1, 'od').fill('22:00');
  await input('Niedziela', 1, 'do').fill('02:00');
  await add('Poniedziałek');
  await input('Poniedziałek', 1, 'od').fill('00:00');
  await input('Poniedziałek', 1, 'do').fill('02:00');
  await save.click();
  await visible(dialog.getByRole('alert'));
  assert.equal(await input('Poniedziałek', 1, 'od').getAttribute('aria-invalid'), 'true');
  await input('Poniedziałek', 1, 'od').fill('02:00');
  await input('Poniedziałek', 1, 'do').fill('23:00');
  const put = page.waitForResponse(r => r.request().method() === 'PUT' && r.url().endsWith('/availability'));
  await save.click();
  assert.equal((await put).status(), 200);
  await visible(dialog.getByRole('status'));
  await dialog.getByRole('button', { name: 'Zamknij', exact: true }).last().click();
  await open.click();
  await visible(input('Niedziela', 1, 'od'));
  assert.equal(await input('Niedziela', 1, 'do').inputValue(), '02:00');
  ok('week-boundary validation, one real PUT, success and GET round trip');
  await dialog.getByRole('button', { name: 'Zamknij cały tydzień' }).click();
  await add('Piątek');
  await input('Piątek', 1, 'od').fill('00:00');
  await input('Piątek', 1, 'do').fill('24:00');
  await save.click();
  await visible(dialog.getByRole('status'));
  assert.equal(await input('Piątek', 1, 'do').inputValue(), '24:00');
  await dialog.getByRole('button', { name: 'Zamknij cały tydzień' }).click();
  const cleared = page.waitForRequest(r => r.method() === 'PUT' && r.url().endsWith('/availability'));
  await save.click();
  assert.deepEqual((await cleared).postDataJSON(), { days: [] });
  await visible(dialog.getByRole('status'));
  ok('real full-day normalization and clearing week with days: []');
  await add('Wtorek');
  await input('Wtorek', 1, 'od').fill('08:00');
  await input('Wtorek', 1, 'do').fill('12:00');
  let mockMode = '400';
  let submissions = 0;
  await page.route('**/api/locations/*/availability', async route => {
    if (route.request().method() !== 'PUT') return route.continue();
    submissions++;
    if (mockMode === 'network') return route.abort('failed');
    if (mockMode === '400') return route.fulfill({ status: 400, json: { detail: 'Błąd harmonogramu testowego.', errors: { 'days[0].intervals[0].from': ['Testowy błąd pola.'] } } });
    if (mockMode === '404') return route.fulfill({ status: 404, json: {} });
    await new Promise(resolve => setTimeout(resolve, 800));
    return route.fulfill({ json: { locationId: 'fixture', timezone: 'Pacific/Auckland', days: [{ dayOfWeek: 3, intervals: [{ from: '09:00', to: '17:00' }] }] } });
  });
  await save.click();
  await visible(dialog.getByText('Testowy błąd pola.'));
  assert.equal(await input('Wtorek', 1, 'od').getAttribute('aria-invalid'), 'true');
  assert.equal(await input('Wtorek', 1, 'od').inputValue(), '08:00');
  ok('fixture 400 detail and sparse request field index mapped to Tuesday');
  mockMode = 'network';
  await save.click();
  await visible(dialog.getByText('Brak połączenia z serwerem. Czy backend działa?'));
  assert.equal(await input('Wtorek', 1, 'od').inputValue(), '08:00');
  mockMode = '404';
  await save.click();
  await visible(dialog.getByText('Ta lokalizacja jest niedostępna. Nie można odczytać ani zapisać jej dostępności.'));
  assert.equal(await dialog.getByRole('status').count(), 0);
  ok('fixture network/404 preserve draft without false success');
  mockMode = 'normalized';
  const before = submissions;
  await save.click();
  assert.equal(await dialog.getByRole('button', { name: 'Zapisywanie…' }).isDisabled(), true);
  assert.equal(await input('Wtorek', 1, 'od').isDisabled(), true);
  await page.keyboard.press('Escape');
  assert.equal(await dialog.count(), 1);
  await visible(dialog.getByRole('status'));
  assert.equal(submissions, before + 1);
  assert.equal(await input('Środa', 1, 'od').inputValue(), '09:00');
  assert.equal(await input('Wtorek', 1, 'od').count(), 0);
  assert.ok((await dialog.innerText()).includes('Pacific/Auckland'));
  ok('fixture pending state, close guard, server response replaces draft and timezone');
  await save.focus();
  await page.keyboard.press('Tab');
  assert.equal(await dialog.getByRole('button', { name: 'Zamknij', exact: true }).first().evaluate(e => e === document.activeElement), true);
  await page.keyboard.press('Shift+Tab');
  assert.equal(await save.evaluate(e => e === document.activeElement), true);
  await page.setViewportSize({ width: 320, height: 740 });
  assert.ok(await dialog.evaluate(e => e.scrollWidth <= e.clientWidth));
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  if (process.env.SCREENSHOT_PATH) await page.screenshot({ path: process.env.SCREENSHOT_PATH });
  await page.keyboard.press('Escape');
  await dialog.waitFor({ state: 'hidden' });
  assert.equal(await open.evaluate(e => e === document.activeElement), true);
  ok('320px mobile layout, keyboard focus loop, Escape and focus restoration');
  const locations = await (await context.request.get('/api/locations')).json();
  const id = locations[0].id;
  const token = await (await context.request.get('/api/csrf')).json();
  const headers = { [token.headerName]: token.token };
  const bad = await context.request.put(`/api/locations/${id}/availability`, { headers, data: { days: [{ dayOfWeek: 1, intervals: [{ from: '08:00', to: '08:00' }] }] } });
  assert.equal(bad.status(), 400);
  const missing = '00000000-0000-0000-0000-000000000099';
  assert.equal((await context.request.get(`/api/locations/${missing}/availability`)).status(), 404);
  assert.equal((await context.request.put(`/api/locations/${missing}/availability`, { headers, data: { days: [] } })).status(), 404);
  assert.equal((await context.request.put(`/api/locations/${id}/availability`, { data: { days: [] } })).status(), 403);
  const anonymous = await browser.newContext({ baseURL });
  assert.equal((await anonymous.request.get(`/api/locations/${id}/availability`)).status(), 401);
  await anonymous.close();
  const company = await browser.newContext({ baseURL });
  const companyPage = await company.newPage();
  await login(companyPage, 'company@example.com');
  await companyPage.waitForURL('**/company');
  await companyPage.goto('/locations');
  await companyPage.waitForURL('**/company');
  assert.equal(await companyPage.getByRole('button', { name: /Dostępność/ }).count(), 0);
  assert.equal((await company.request.get(`/api/locations/${id}/availability`)).status(), 403);
  await company.close();
  ok('real API 400/404/401/CSRF 403, foreign role route and endpoint 403');
  const longNight = { days: [{ dayOfWeek: 7, intervals: [{ from: '22:00', to: '24:00' }] }, { dayOfWeek: 1, intervals: [{ from: '00:00', to: '23:00' }] }] };
  const longResponse = await context.request.put(`/api/locations/${id}/availability`, { headers, data: longNight });
  assert.equal(longResponse.status(), 200);
  const normalized = await longResponse.json();
  assert.deepEqual(normalized.days.map(d => d.dayOfWeek), [1, 7]);
  assert.equal(normalized.days[1].intervals[0].to, '24:00');
  const resaved = await context.request.put(`/api/locations/${id}/availability`, { headers, data: { days: normalized.days } });
  assert.deepEqual((await resaved.json()).days, normalized.days);
  const multi = { days: [{ dayOfWeek: 2, intervals: [{ from: '08:00', to: '12:00' }, { from: '14:00', to: '18:00' }] }] };
  assert.equal((await context.request.put(`/api/locations/${id}/availability`, { headers, data: multi })).status(), 200);
  assert.deepEqual((await (await context.request.get(`/api/locations/${id}/availability`)).json()).days, multi.days);
  assert.equal((await context.request.put(`/api/locations/${id}/availability`, { headers, data: { days: [] } })).status(), 200);
  ok('real long Sunday/Monday normalization and resave, multiple windows, final empty week');
  await page.unroute('**/api/locations/*/availability');
  await page.reload();
  await visible(open);
  let releaseGet;
  const getGate = new Promise(resolve => { releaseGet = resolve; });
  await page.route('**/api/locations/*/availability', async route => {
    await getGate;
    return route.fulfill({ status: 404, json: {} });
  });
  await open.click();
  await visible(dialog.getByLabel('Ładowanie dostępności'));
  releaseGet();
  await visible(dialog.getByText('Ta lokalizacja jest niedostępna. Nie można odczytać ani zapisać jej dostępności.'));
  assert.equal(await dialog.getByRole('button', { name: 'Zapisz dostępność' }).count(), 0);
  ok('fixture initial loading and GET 404 without editable form');
  assert.deepEqual(runtimeErrors, []);
} finally {
  await browser.close();
}
